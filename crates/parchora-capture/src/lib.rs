//! 剪贴板捕捉状态机（TASK-300）：0.5s 轮询的拍级逻辑、8 类判定链消费、隐私
//! 拒收、前台应用排除、10s SHA256 判重——**判定与判重机制归本 crate，投递与
//! 持久化归 app 宿主**（REQ-CAPTURE-POLL/8TYPES/PRIVACY/EXCLUDE/DEDUPE）。
//!
//! 分层与注入面（TASK-300 时序测试口径）：
//! - 板面读写经 [`PasteboardSource`] trait 注入（生产桥 = parchora-platform
//!   `pasteboard_board`/`pasteboard_change_count`，app 装配实现）；
//! - 前台应用经 [`FrontmostApp`] trait 注入（生产桥 = platform
//!   `frontmost_bundle_id`）；
//! - 判重时间源以 `now: Instant` 参数逐拍注入（无隐式时钟——测试以
//!   `Instant::now().checked_sub(..)` 构造任意拍点，确定性覆盖
//!   SCN-CAPTURE-* 状态时序全族）。
//!
//! 判定链序（权威 = core::classify 文档；本 crate 仅消费）：
//! 基线播种 → 变化检测 → 隐私拒收 → **前台排除** → 8 类 classify → 载荷装配。

use std::collections::VecDeque;
use std::time::{Duration, Instant};

use parchora_core::classify::{classify, PasteboardKind, PasteboardTypeSnapshot};
use parchora_core::content::ContentType;
use parchora_core::hash::sha256_hex;

/// 判重窗（REQ-CAPTURE-DEDUPE：同内容 10s 只入库一次）唯一常量源。
pub const DEDUPE_WINDOW_SECS: u64 = 10;

/// 板面内容采样（桥面三态）：
/// - `Empty`：板上无任何类型（空复制不产生条目）；
/// - `Rejected`：隐私标记命中（Transient/Concealed/AutoGenerated · 100% 拒收）；
/// - `Snapshots`：类型快照全集（逐类载荷可备）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BoardContent {
    Empty,
    Rejected,
    Snapshots(Vec<PasteboardTypeSnapshot>),
}

/// 板面读写注入面（生产 = platform 桥装配；测试 = 假板注入）。
/// `None` 语义 = 桥失败/类缺失（本轮无证据，基线保持——下拍自愈）。
pub trait PasteboardSource {
    fn change_count(&self) -> Option<u64>;
    fn board(&self) -> Option<BoardContent>;
}

/// 前台应用注入面（生产 = NSWorkspace frontmostApplication；测试 = 直给）。
pub trait FrontmostApp {
    fn bundle_id(&self) -> Option<String>;
}

/// 拍级捕获产出：判定结果 + 载荷（hash 与 blobs 落库由宿主消费）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Captured {
    /// 8 类判定结果（classify 链输出 · DB CHECK 值域同源）。
    pub content_type: ContentType,
    /// 文本类载荷（plainText 原文 / html 源文 / color hex / fileURL 列表；
    /// image 类为 None——二进制载荷在 `image_bytes`）。
    pub text: Option<String>,
    /// 二进制载荷（image 原始字节 · blobs 落库与 hash 承载）。
    pub image_bytes: Option<Vec<u8>>,
}

impl Captured {
    /// 内容指纹（REQ-CAPTURE-DEDUPE · DB content_hash 同源）：
    /// 二进制类 hash 原始字节；文本类（含空载荷的 unknown）hash UTF-8 载荷，
    /// 无载荷时以判定类名字节兜底（确定性——同判定同指纹，防 None 哈希漂移）。
    pub fn content_hash(&self) -> String {
        if let Some(bytes) = &self.image_bytes {
            sha256_hex(bytes)
        } else {
            match &self.text {
                Some(text) => sha256_hex(text.as_bytes()),
                None => sha256_hex(self.content_type.as_db_value().as_bytes()),
            }
        }
    }
}

/// 10s 判重 LRU（REQ-CAPTURE-DEDUPE）：同内容指纹窗内只放行一次。
///
/// 载荷 = (内容指纹 sha256 hex, 捕获时刻)；逐拍滚动剔除过期项。容量上限
/// `MAX_ENTRIES` 为防滥用兜底（正常 10s 窗内项数远小于此）。
#[derive(Debug)]
pub struct DedupeLru {
    window: Duration,
    entries: VecDeque<(String, Instant)>,
}

impl DedupeLru {
    /// 容量兜底（10s 窗 × 0.5s 拍距的若干倍量级；防注入滥用无界增长）。
    pub const MAX_ENTRIES: usize = 512;

    pub fn new() -> Self {
        Self::with_window(Duration::from_secs(DEDUPE_WINDOW_SECS))
    }

    pub fn with_window(window: Duration) -> Self {
        Self {
            window,
            entries: VecDeque::new(),
        }
    }

    /// 放行判定：true = 新内容（登记并放行）；false = 窗内重复（拒收）。
    /// 过期项在每次判定时滚动剔除（无独立清扫拍）。
    pub fn admit(&mut self, hash: &str, now: Instant) -> bool {
        self.prune(now);
        if self.entries.iter().any(|(h, _)| h == hash) {
            return false;
        }
        self.entries.push_back((hash.to_string(), now));
        while self.entries.len() > Self::MAX_ENTRIES {
            self.entries.pop_front();
        }
        true
    }

    /// 跨会话播种（启动回填口径）：按墙钟年龄折算的回拨时刻登记既有指纹——
    /// 窗外项（含重启后的全部历史）由 `Instant` 语义自然过期，不误拒。回拨失败
    ///（年龄超出当前进程 `Instant` 可表达范围）视为窗外，不播种不误拒。
    pub fn seed(&mut self, hash: &str, captured_wall: i64, now_wall: i64, now: Instant) {
        let Ok(age) = u64::try_from(now_wall.saturating_sub(captured_wall)) else {
            return; // 防御：异常墙序（captured > now）→ 不播种不误拒
        };
        let Some(at) = now.checked_sub(Duration::from_secs(age)) else {
            return; // 回拨越界 = 项龄大于进程运行时长 → 必然窗外
        };
        if now.duration_since(at) >= self.window {
            return; // 窗外：不播种（诚实语义——重启时刻窗外无判重约束）
        }
        self.entries.push_back((hash.to_string(), at));
    }

    fn prune(&mut self, now: Instant) {
        self.entries
            .retain(|(_, at)| now.duration_since(*at) < self.window);
    }

    /// 诊断/测试读点（条目数）。
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }
}

impl Default for DedupeLru {
    fn default() -> Self {
        Self::new()
    }
}

/// 捕捉状态机：changeCount 基线 + 判定链 + 载荷装配。单拍入口 [`Engine::tick`]。
#[derive(Debug, Default)]
pub struct Engine {
    /// 上次 changeCount（None = 待首拍播种——首拍只记基线不捕获）。
    last_change: Option<u64>,
}

impl Engine {
    pub fn new() -> Self {
        Self::default()
    }

    /// 基线读点（诊断/测试）。
    pub fn last_change(&self) -> Option<u64> {
        self.last_change
    }

    /// 单拍（SCN-CAPTURE-* 状态时序承载）：
    /// 1. changeCount 缺失（桥失败）→ None 且基线保持；
    /// 2. 首拍 → 播种基线，不捕获（SCN-BOOT-BASELINE）；
    /// 3. 未变化 → None，不读板面（REQ-CAPTURE-POLL）；
    /// 4. 变化命中 → 读板面：隐私拒收 → 空板 → **前台排除**（判定链序位）→
    ///    classify → 载荷装配。
    pub fn tick<P: PasteboardSource + ?Sized, F: FrontmostApp + ?Sized>(
        &mut self,
        pb: &P,
        frontmost: &F,
        excludes: &[String],
    ) -> Option<Captured> {
        let count = pb.change_count()?;
        match self.last_change {
            None => {
                self.last_change = Some(count);
                return None;
            }
            Some(prev) if prev == count => return None,
            Some(_) => self.last_change = Some(count),
        }
        let board = pb.board()?;
        let snapshots = match board {
            BoardContent::Rejected => return None, // REQ-CAPTURE-PRIVACY（最前）
            BoardContent::Empty => return None,
            BoardContent::Snapshots(s) => s,
        };
        // 前台排除（REQ-CAPTURE-EXCLUDE · 判定链序在隐私过滤之后）：前台应用
        // 命中排除列表 → 永久丢弃（返回 None，不入任何缓冲）。
        if let Some(fid) = frontmost.bundle_id() {
            if excludes.iter().any(|e| e == &fid) {
                return None;
            }
        }
        let content_type = classify(&snapshots)?;
        Some(Self::assemble(content_type, &snapshots))
    }

    /// 载荷装配（classify 结果 → 文本/二进制载荷选择）：
    /// - Color：色票 hex 文本（如 `#FF8800`）；Image：原始字节；
    /// - FileUrl：全部文件 URL 按行拼接；
    /// - Url/Html/PlainText：对应类首条文本载荷；
    /// - RichText：优先纯文本载荷（板面常同携），无则 RTF 源文（偏差登记
    ///   DEC-187：RTF→纯文本转换未实装）；
    /// - Unknown：任一可用文本，无则 None（hash 走指纹兜底）。
    fn assemble(content_type: ContentType, snapshots: &[PasteboardTypeSnapshot]) -> Captured {
        let text_of = |kind: PasteboardKind| -> Option<String> {
            snapshots
                .iter()
                .find(|s| s.kind == kind)
                .and_then(|s| s.text.clone())
        };
        let (text, image_bytes) = match content_type {
            ContentType::Color => (text_of(PasteboardKind::Color), None),
            ContentType::Image => (
                None,
                snapshots
                    .iter()
                    .find(|s| s.kind == PasteboardKind::Image)
                    .and_then(|s| s.bytes.clone()),
            ),
            ContentType::FileUrl => {
                let mut urls: Vec<String> = snapshots
                    .iter()
                    .filter(|s| s.kind == PasteboardKind::FileUrl)
                    .filter_map(|s| s.text.clone())
                    .filter(|t| !t.is_empty())
                    .collect();
                urls.dedup();
                (
                    if urls.is_empty() {
                        None
                    } else {
                        Some(urls.join("\n"))
                    },
                    None,
                )
            }
            ContentType::Url | ContentType::PlainText => (text_of(PasteboardKind::PlainText), None),
            ContentType::Html => (
                text_of(PasteboardKind::Html).or_else(|| text_of(PasteboardKind::PlainText)),
                None,
            ),
            ContentType::RichText => (
                text_of(PasteboardKind::PlainText).or_else(|| text_of(PasteboardKind::RichText)),
                None,
            ),
            ContentType::Unknown => (snapshots.iter().find_map(|s| s.text.clone()), None),
        };
        Captured {
            content_type,
            text,
            image_bytes,
        }
    }
}

