    #[test]
    fn dedupe_prunes_and_caps() {
        let mut lru = DedupeLru::with_window(Duration::from_secs(1));
        let now = Instant::now();
        let stale = now.checked_sub(Duration::from_secs(5)).unwrap();
        for i in 0..64 {
            assert!(lru.admit(&format!("stale-{i}"), stale));
        }
        assert!(lru.admit("fresh", now));
        // 旧项被 prune（fresh 判定时过期项全清）。
        assert_eq!(lru.len(), 1, "过期项滚动剔除");
        let mut big = DedupeLru::new();
        let now = Instant::now();
        for i in 0..(DedupeLru::MAX_ENTRIES + 40) {
            let _ = big.admit(&format!("h{i}"), now);
        }
        assert_eq!(big.len(), DedupeLru::MAX_ENTRIES, "容量兜底截断");
    }

    #[test]
    fn dedupe_seed_honors_wall_age() {
        let mut lru = DedupeLru::new();
        let now = Instant::now();
        let now_wall = 1_000_000i64;
        // 窗内播种（3s 前）→ admit 拒收（seed 即生效）。
        lru.seed("recent", now_wall - 3, now_wall, now);
        assert_eq!(lru.len(), 1);
        assert!(!lru.admit("recent", now), "窗内播种指纹拒收");
        // 窗外播种 → no-op（诚实语义：重启时刻窗外无判重约束）。
        lru.seed("ancient", now_wall - 3600, now_wall, now);
        assert_eq!(lru.len(), 1, "窗外项不播种");
        // 窗外的历史项 admit 正常放行（seed 不残留）。
        assert!(lru.admit("ancient", now));
    }

    // ---- 捕获→分类→判重组合流水线（TASK-300 状态时序全链）----

    #[test]
    fn pipeline_capture_then_dedupe_then_expiry() {
        let mut eng = Engine::new();
        let mut lru = DedupeLru::new();
        let app = FxApp { id: None };
        let board = BoardContent::Snapshots(vec![snap(PasteboardKind::PlainText, "同一份内容")]);
        let mut pb0 = ManualPb::new(vec![1, 2, 3], board.clone());
        assert!(eng.tick(&pb0, &app, &[]).is_none(), "基线拍");
        pb0.bump();
        let cap1 = eng.tick(&pb0, &app, &[]).expect("变化拍");
        let h = cap1.content_hash();
        let t0 = Instant::now();
        assert!(lru.admit(&h, t0), "首见入库放行");

        // 同内容 10s 窗内再次复制（changeCount 推进）→ 判重拒收。
        pb0.bump();
        let cap2 = eng.tick(&pb0, &app, &[]).expect("变化拍");
        assert_eq!(cap2.content_hash(), h);
        assert!(
            !lru.admit(&h, t0.checked_add(Duration::from_millis(500)).unwrap()),
            "10s 窗内拒收"
        );

        // 11s 后同内容 → 窗过期再放行。
        let t11 = t0.checked_add(Duration::from_secs(11)).unwrap();
        assert!(lru.admit(&h, t11), "超窗再放行");
        assert_eq!(lru.len(), 1, "过期项剔除后仅剩新项");
    }
