    #[test]
    fn classify_chain_payloads() {
        struct Case {
            snaps: Vec<PasteboardTypeSnapshot>,
            want_ct: ContentType,
            want_text: Option<&'static str>,
        }
        let cases = vec![
            // 链序：color → image → fileURL → url（纯文本改判）→ html → richText → plainText
            Case {
                snaps: vec![
                    snap(PasteboardKind::Color, "#FF8800"),
                    snap(PasteboardKind::PlainText, "https://e.io"),
                ],
                want_ct: ContentType::Color,
                want_text: Some("#FF8800"),
            },
            Case {
                snaps: vec![
                    PasteboardTypeSnapshot::with_bytes(PasteboardKind::Image, vec![1, 2, 3]),
                    snap(PasteboardKind::PlainText, "正文"),
                ],
                want_ct: ContentType::Image,
                want_text: None,
            },
            Case {
                snaps: vec![
                    snap(PasteboardKind::FileUrl, "file:///A.md"),
                    snap(PasteboardKind::FileUrl, "file:///B.md"),
                    snap(PasteboardKind::PlainText, "https://e.io"),
                ],
                want_ct: ContentType::FileUrl,
                want_text: Some("file:///A.md\nfile:///B.md"),
            },
            Case {
                snaps: vec![snap(PasteboardKind::PlainText, "https://e.io/x")],
                want_ct: ContentType::Url,
                want_text: Some("https://e.io/x"),
            },
            Case {
                snaps: vec![
                    snap(PasteboardKind::PlainText, "https://e.io"),
                    snap(PasteboardKind::Html, "<b>粗</b>"),
                ],
                want_ct: ContentType::Url,
                want_text: Some("https://e.io"),
            },
            Case {
                snaps: vec![
                    snap(PasteboardKind::Html, "<b>粗</b>"),
                    snap(PasteboardKind::PlainText, "正文"),
                ],
                want_ct: ContentType::Html,
                want_text: Some("<b>粗</b>"),
            },
            Case {
                snaps: vec![
                    snap(PasteboardKind::RichText, "{\\rtf1 源文}"),
                    snap(PasteboardKind::PlainText, "正文"),
                ],
                want_ct: ContentType::RichText,
                want_text: Some("正文"),
            },
            Case {
                snaps: vec![snap(PasteboardKind::RichText, "{\\rtf1 源文}")],
                want_ct: ContentType::RichText,
                want_text: Some("{\\rtf1 源文}"),
            },
            Case {
                snaps: vec![snap(PasteboardKind::PlainText, "普通文本")],
                want_ct: ContentType::PlainText,
                want_text: Some("普通文本"),
            },
            Case {
                snaps: vec![PasteboardTypeSnapshot::presence(PasteboardKind::Other)],
                want_ct: ContentType::Unknown,
                want_text: None,
            },
        ];
        for c in cases {
            let pb = ManualPb::new(vec![10, 11], BoardContent::Snapshots(c.snaps.clone()));
            let mut eng = Engine::new();
            eng.tick(&pb, &FxApp { id: None }, &[]);
            let got = eng
                .tick(
                    &ManualPb::new(vec![11, 12], BoardContent::Snapshots(c.snaps)),
                    &FxApp { id: None },
                    &[],
                )
                .expect("变化拍应产出");
            assert_eq!(got.content_type, c.want_ct, "ct: {:?}", got);
            assert_eq!(got.text.as_deref(), c.want_text, "text: {:?}", got);
        }
    }

