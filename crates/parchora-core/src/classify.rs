//! 捕捉层类型判定与隐私拒收（TASK-101）。
//!
//! 锚点：REQ-CAPTURE-8TYPES（8 类固定优先级判定链）/ REQ-CAPTURE-PRIVACY（C5 三标记 100% 拒收）；
//! CB 逆向依据：类型判定硬编码 if 链「隐私过滤 → color → image → fileURL → URL → html → rtf →
//! plainText」（Clipbara-产品文档 §2.1，Services/ContentTypeClassifier.swift:16-83、:75-80）。
//!
//! 口径说明：隐私过滤由 [`is_rejected_content`] 独立承载、调用方置于分类链最前（TASK-101
//! 「classify 与 is_rejected_content」双函数口径）；design §3.4 草案注「隐私过滤在内」为草案
//! 措辞，偏差登记见 DEC-63。

use crate::content::ContentType;
use serde::{Deserialize, Serialize};

/// macOS 系统隐私标记（C5 / REQ-CAPTURE-PRIVACY；nspasteboard.org 私有标记约定）
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct PrivacyMarkers {
    pub transient: bool,
    pub concealed: bool,
    pub auto_generated: bool,
}

/// C5 / REQ-CAPTURE-PRIVACY / SCN-CAPTURE-PRIVACY-REJECT：
/// Transient / Concealed / AutoGenerated 任一命中即拒收；隐私过滤在分类链最前。
pub fn is_rejected_content(markers: &PrivacyMarkers) -> bool {
    markers.transient || markers.concealed || markers.auto_generated
}

/// 板面类型快照：`kind` 表示剪贴板上是否存在该类数据；文本类可携带载荷
///（URL 改判取纯文本载荷判定——CB `:75-80`）；二进制类（image）携带原始字节
///（TASK-300 流水线载荷装配 · hash 与 blobs 落库消费）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PasteboardTypeSnapshot {
    pub kind: PasteboardKind,
    pub text: Option<String>,
    pub bytes: Option<Vec<u8>>,
}

impl PasteboardTypeSnapshot {
    pub fn presence(kind: PasteboardKind) -> Self {
        PasteboardTypeSnapshot {
            kind,
            text: None,
            bytes: None,
        }
    }
    pub fn with_text(kind: PasteboardKind, text: impl Into<String>) -> Self {
        PasteboardTypeSnapshot {
            kind,
            text: Some(text.into()),
            bytes: None,
        }
    }
    /// 二进制载荷快照（image 原始字节；TASK-300 桥面装配入口）。
    pub fn with_bytes(kind: PasteboardKind, bytes: impl Into<Vec<u8>>) -> Self {
        PasteboardTypeSnapshot {
            kind,
            text: None,
            bytes: Some(bytes.into()),
        }
    }
}

/// 剪贴板数据类目（快照级；`Other` 承载本产品不映射的板面类型 → 分类为 unknown）
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum PasteboardKind {
    PlainText,
    RichText,
    Html,
    Image,
    FileUrl,
    Color,
    Other,
}

/// REQ-CAPTURE-8TYPES / SCN-CAPTURE-CLASSIFY-PRIORITY：固定优先级判定链。
///
/// 链序：color → image → fileURL → URL（纯文本具 scheme+host）→ html → richText → plainText，
/// 全不命中 → unknown；空输入（无任何数据）→ None（无内容可捕捉）。
/// 隐私过滤由调用方以 [`is_rejected_content`] 置于最前（REQ-CAPTURE-PRIVACY）。
pub fn classify(types: &[PasteboardTypeSnapshot]) -> Option<ContentType> {
    if types.is_empty() {
        return None; // 剪贴板无内容 → 不产生条目（CB 判定入口）
    }
    let has = |kind: PasteboardKind| types.iter().any(|t| t.kind == kind);

    if has(PasteboardKind::Color) {
        return Some(ContentType::Color);
    }
    if has(PasteboardKind::Image) {
        return Some(ContentType::Image);
    }
    if has(PasteboardKind::FileUrl) {
        return Some(ContentType::FileUrl);
    }
    // URL 改判（CB :75-80）：纯文本同时具备 scheme 与 host → url
    if types
        .iter()
        .any(|t| t.kind == PasteboardKind::PlainText && t.text.as_deref().is_some_and(is_url_text))
    {
        return Some(ContentType::Url);
    }
    if has(PasteboardKind::Html) {
        return Some(ContentType::Html);
    }
    if has(PasteboardKind::RichText) {
        return Some(ContentType::RichText);
    }
    if has(PasteboardKind::PlainText) {
        return Some(ContentType::PlainText);
    }
    Some(ContentType::Unknown)
}

/// 「同时具备 URL scheme 与 host」的最小判定（REQ-CAPTURE-8TYPES 场景；
/// CB 按纯文本整体判——取舍与假设登记见 DEC-63）：
/// 裁剪后整段文本 = `scheme://host…`，scheme 首字符为字母、其余为字母/数字/`+-.`，
/// host 非空且截至 `/ ? #`（不含空白与控制字符，整段含换行判否）。
pub fn is_url_text(text: &str) -> bool {
    let trimmed = text.trim();
    let Some(scheme_end) = trimmed.find("://") else {
        return false;
    };
    if scheme_end == 0 {
        return false;
    }
    let scheme = &trimmed[..scheme_end];
    let mut scheme_chars = scheme.chars();
    if !scheme_chars.next().is_some_and(|c| c.is_ascii_alphabetic()) {
        return false;
    }
    if !scheme_chars.all(|c| c.is_ascii_alphanumeric() || matches!(c, '+' | '-' | '.')) {
        return false;
    }
    let rest = &trimmed[scheme_end + 3..];
    let host = rest.split(['/', '?', '#']).next().unwrap_or("");
    !host.is_empty() && !host.chars().any(|c| c.is_whitespace() || c.is_control())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::content::{Clip, ContentType};

    // ---- C5 隐私拒收（REQ-CAPTURE-PRIVACY）----

    #[test]
    fn privacy_rejects_each_marker_alone() {
        for markers in [
            PrivacyMarkers {
                transient: true,
                ..Default::default()
            },
            PrivacyMarkers {
                concealed: true,
                ..Default::default()
            },
            PrivacyMarkers {
                auto_generated: true,
                ..Default::default()
            },
            PrivacyMarkers::default(),
        ] {
            let expected = markers != PrivacyMarkers::default();
            assert_eq!(
                is_rejected_content(&markers),
                expected,
                "markers={markers:?}"
            );
        }
    }

    #[test]
    fn privacy_rejects_any_combination() {
        // 三标记组合：任一命中即拒收
        assert!(is_rejected_content(&PrivacyMarkers {
            transient: true,
            concealed: true,
            auto_generated: false
        }));
        assert!(is_rejected_content(&PrivacyMarkers {
            transient: false,
            concealed: true,
            auto_generated: true
        }));
        assert!(is_rejected_content(&PrivacyMarkers {
            transient: true,
            concealed: true,
            auto_generated: true
        }));
        assert!(!is_rejected_content(&PrivacyMarkers::default()));
    }

    #[test]
    fn privacy_filters_before_type_chain() {
        // SCN-CAPTURE-PRIVACY-REJECT：同时携带隐私标记与普通文本类型，仍按拒收处理
        let markers = PrivacyMarkers {
            transient: true,
            ..Default::default()
        };
        let types = [PasteboardTypeSnapshot::with_text(
            PasteboardKind::PlainText,
            "https://example.com",
        )];
        // 判定顺序契约：拒收判定在前，命中即不进入 classify（不入库）
        if is_rejected_content(&markers) {
            // 拒收路径：不产生条目（捕捉层不再调用 classify）
        } else {
            unreachable!("隐私标记命中必须拒收");
        }
        let _ = types; // 分类链未被触达
        assert!(is_rejected_content(&markers));
        assert_eq!(classify(&[]), None); // 佐证空输入路径
    }

    // ---- 8 类判定链（REQ-CAPTURE-8TYPES / SCN-CAPTURE-CLASSIFY-PRIORITY）----

    #[test]
    fn classifies_color_over_everything() {
        let types = [
            PasteboardTypeSnapshot::presence(PasteboardKind::Color),
            PasteboardTypeSnapshot::presence(PasteboardKind::Image),
            PasteboardTypeSnapshot::with_text(PasteboardKind::PlainText, "https://example.com"),
            PasteboardTypeSnapshot::presence(PasteboardKind::Html),
        ];
        assert_eq!(classify(&types), Some(ContentType::Color));
    }

    #[test]
    fn classifies_image_over_html_and_text() {
        // 「同时携带图片与 RTF 数据 → image」（image 在 richText 之前）
        let types = [
            PasteboardTypeSnapshot::presence(PasteboardKind::Image),
            PasteboardTypeSnapshot::presence(PasteboardKind::RichText),
            PasteboardTypeSnapshot::with_text(PasteboardKind::PlainText, "hello"),
        ];
        assert_eq!(classify(&types), Some(ContentType::Image));
    }

    #[test]
    fn classifies_file_url_over_url_and_html() {
        let types = [
            PasteboardTypeSnapshot::presence(PasteboardKind::FileUrl),
            PasteboardTypeSnapshot::with_text(PasteboardKind::PlainText, "https://example.com"),
            PasteboardTypeSnapshot::presence(PasteboardKind::Html),
        ];
        assert_eq!(classify(&types), Some(ContentType::FileUrl));
    }

    #[test]
    fn plain_text_with_scheme_and_host_becomes_url() {
        // 「只有纯文本但该文本同时具备 URL scheme 与 host → url 而非 plainText」
        let types = [PasteboardTypeSnapshot::with_text(
            PasteboardKind::PlainText,
            "https://example.com/path?q=1",
        )];
        assert_eq!(classify(&types), Some(ContentType::Url));
    }

    #[test]
    fn url_probe_wins_over_html_per_chain_order() {
        // 链序 URL 位于 html 之前（CB if 链字面序）
        let types = [
            PasteboardTypeSnapshot::with_text(PasteboardKind::PlainText, "http://a.io"),
            PasteboardTypeSnapshot::presence(PasteboardKind::Html),
        ];
        assert_eq!(classify(&types), Some(ContentType::Url));
    }

    #[test]
    fn html_over_rich_text_over_plain_text() {
        let types = [
            PasteboardTypeSnapshot::presence(PasteboardKind::Html),
            PasteboardTypeSnapshot::presence(PasteboardKind::RichText),
            PasteboardTypeSnapshot::with_text(PasteboardKind::PlainText, "body"),
        ];
        assert_eq!(classify(&types), Some(ContentType::Html));

        let types = [
            PasteboardTypeSnapshot::presence(PasteboardKind::RichText),
            PasteboardTypeSnapshot::with_text(PasteboardKind::PlainText, "body"),
        ];
        assert_eq!(classify(&types), Some(ContentType::RichText));

        let types = [PasteboardTypeSnapshot::with_text(
            PasteboardKind::PlainText,
            "body",
        )];
        assert_eq!(classify(&types), Some(ContentType::PlainText));
    }

    #[test]
    fn unmapped_types_classify_as_unknown() {
        let types = [PasteboardTypeSnapshot::presence(PasteboardKind::Other)];
        assert_eq!(classify(&types), Some(ContentType::Unknown));
    }

    #[test]
    fn empty_input_is_none() {
        assert_eq!(classify(&[]), None);
    }

    // ---- is_url_text 判定 ----

    #[test]
    fn url_text_positive_cases() {
        for s in [
            "https://example.com",
            "http://a.io/x?y#z",
            "FTP://Host",
            "  https://a.b  ",
        ] {
            assert!(is_url_text(s), "{s}");
        }
    }

    #[test]
    fn url_text_negative_cases() {
        for s in [
            "example.com",         // 无 scheme
            "https://",            // 无 host
            "://example.com",      // 空 scheme
            "1http://a.io",        // scheme 首字符非字母
            "ht tp://a.io",        // scheme 含空白
            "mailto:user@x.com",   // 无 :// 层级部分（取舍见 DEC-63）
            "普通文本",            // 无 scheme
            "http://a.io\n第二行", // 多行整段判否
            "http://a b.io",       // host 含空白
        ] {
            assert!(!is_url_text(s), "{s}");
        }
    }

    #[test]
    fn clip_content_type_aligns_with_classify_output() {
        // core 内两条链一致：classify 结果可直填 Clip.content_type（DB CHECK 值域）
        let types = [PasteboardTypeSnapshot::presence(PasteboardKind::Color)];
        let ct = classify(&types).unwrap();
        let clip = Clip {
            id: uuid::Uuid::nil(),
            content_type: ct,
            text_content: None,
            content_hash: "hash".into(),
            source_app: None,
            size: 0,
            is_pinned: false,
            blob_rel_path: None,
            thumb_rel_path: None,
            edited_at: None,
            created_at: "2026-10-17T08:00:00Z".into(),
        };
        assert_eq!(clip.content_type.as_db_value(), "color");
    }
}
